// Regenerates the typed API client from the backend's OpenAPI schema.
// Usage: pnpm gen:api   (needs uv; CI fails if the committed files are out of date)
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import openapiTS, { astToString } from 'openapi-typescript';

const frontend = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const backend = path.join(frontend, '..', 'backend');
const outDir = path.join(frontend, 'src', 'api', 'generated');
const schemaFile = path.join(outDir, 'openapi.json');
const typesFile = path.join(outDir, 'schema.d.ts');

mkdirSync(outDir, { recursive: true });
execFileSync(
  'uv',
  ['run', '--project', backend, 'python', '-m', 'homestead_finance.openapi', schemaFile],
  { stdio: 'inherit' },
);

const ast = await openapiTS(pathToFileURL(schemaFile));
const header =
  '// Generated by `pnpm gen:api` from the backend OpenAPI schema. Do not edit by hand.\n\n';
writeFileSync(typesFile, header + astToString(ast), 'utf8');
console.log(
  `Wrote ${path.relative(frontend, schemaFile)} and ${path.relative(frontend, typesFile)}`,
);
